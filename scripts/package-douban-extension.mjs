import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const folder = resolve(root, 'browser-extension/douban');
const generated = resolve(root, 'lib/douban-extension-package.generated.ts');
const parserFile = resolve(folder, 'collector-parser.js');
const detailsParserFile = resolve(folder, 'details-parser.js');
const names = ['manifest.json', 'background.js', 'details-parser.js', 'collector-parser.js', 'collector.js', 'README.md'];
const siteMatch = 'https://jiashu-life-os-health.jiashuh329.chatgpt.site/*';

export function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/** Stored entries make identical sources produce the same ZIP on supported Node releases. */
export function createExtensionZip(files) {
  const local = [], central = []; let offset = 0;
  for (const [name, value] of files) {
    if (!names.includes(name)) throw new Error('Unexpected extension package path');
    const fileName = Buffer.from(name), body = Buffer.from(value), crc = crc32(body);
    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50); header.writeUInt16LE(20, 4); header.writeUInt16LE(0x800, 6);
    header.writeUInt16LE(33, 12); header.writeUInt32LE(crc, 14);
    header.writeUInt32LE(body.length, 18); header.writeUInt32LE(body.length, 22); header.writeUInt16LE(fileName.length, 26);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50); entry.writeUInt16LE(20, 4); entry.writeUInt16LE(20, 6); entry.writeUInt16LE(0x800, 8);
    entry.writeUInt16LE(33, 14); entry.writeUInt32LE(crc, 16); entry.writeUInt32LE(body.length, 20);
    entry.writeUInt32LE(body.length, 24); entry.writeUInt16LE(fileName.length, 28); entry.writeUInt32LE(offset, 42);
    local.push(header, fileName, body); central.push(entry, fileName); offset += header.length + fileName.length + body.length;
  }
  const directory = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, directory, end]);
}

async function expectedParser() {
  const allowed = new Set(['douban-browser-collector.ts', 'douban-details-parser.ts', 'douban-details.ts'].map(name => resolve(root, 'lib', name)));
  const cache = new Map();
  async function localModule(filename, ancestors = new Set()) {
    if (!allowed.has(filename) || ancestors.has(filename)) throw new Error('Unexpected extension parser dependency');
    if (cache.has(filename)) return cache.get(filename);
    const source = await readFile(filename, 'utf8');
    let js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: true } }).outputText;
    const ast = ts.createSourceFile(filename, js, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS);
    const replacements = [];
    for (const statement of ast.statements) if (ts.isImportDeclaration(statement)) {
      const specifier = statement.moduleSpecifier;
      if (!ts.isStringLiteral(specifier) || !specifier.text.startsWith('./')) throw new Error('Extension parsers must use reviewed local dependencies');
      const dependency = fileURLToPath(new URL(specifier.text, pathToFileURL(filename)));
      const url = await localModule(dependency, new Set([...ancestors, filename]));
      replacements.push({ start: specifier.getStart(ast), end: specifier.end, value: JSON.stringify(url) });
    }
    for (const replacement of replacements.reverse()) js = js.slice(0, replacement.start) + replacement.value + js.slice(replacement.end);
    const url = 'data:text/javascript;base64,' + Buffer.from(js).toString('base64');
    cache.set(filename, url); return url;
  }
  const module = await import(await localModule(resolve(root, 'lib/douban-browser-collector.ts')));
  return '// Generated by scripts/package-douban-extension.mjs.\n'
    + 'globalThis.JiashuDoubanCollectorFactory = ' + module.renderDoubanBrowserCollectorFactory() + ';\n';
}

export async function extensionPackage(check = true) {
  const parser = await expectedParser();
  const detailsSource = await readFile(resolve(root, 'lib/douban-details.ts'), 'utf8');
  const detailsJs = ts.transpileModule(detailsSource, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: true } }).outputText;
  const detailsModule = await import('data:text/javascript;base64,' + Buffer.from(detailsJs).toString('base64'));
  const detailsParser = '// Generated by scripts/package-douban-extension.mjs.\nconst detailsParser = '
    + detailsModule.renderDoubanDetailsParserFactory() + '();\nexport function parseDoubanDetails(raw) { return detailsParser.parse(raw); }\n';
  if (check) {
    if (await readFile(parserFile, 'utf8') !== parser) throw new Error('Extension parser is stale. Run node scripts/package-douban-extension.mjs');
    if (await readFile(detailsParserFile, 'utf8') !== detailsParser) throw new Error('Extension details validator is stale. Run node scripts/package-douban-extension.mjs');
  } else { await mkdir(folder, { recursive: true }); await writeFile(parserFile, parser); await writeFile(detailsParserFile, detailsParser); }
  const files = await Promise.all(names.map(async name => [name, await readFile(resolve(folder, name))]));
  const manifest = JSON.parse(files[0][1].toString('utf8'));
  const extensionId = createHash('sha256').update(Buffer.from(manifest.key, 'base64')).digest('hex').slice(0, 32)
    .split('').map(c => String.fromCharCode(97 + parseInt(c, 16))).join('');
  const config = await readFile(resolve(root, 'lib/douban-extension.ts'), 'utf8');
  const hosts = ['https://movie.douban.com/*', 'https://book.douban.com/*', 'https://music.douban.com/*'];
  if (manifest.manifest_version !== 3 || !config.includes("'" + extensionId + "'")
    || JSON.stringify([...manifest.permissions].sort()) !== JSON.stringify(['scripting', 'tabs'])
    || JSON.stringify(manifest.externally_connectable?.matches) !== JSON.stringify([siteMatch])
    || JSON.stringify([...manifest.host_permissions].sort()) !== JSON.stringify(hosts.sort())
    || manifest.background?.service_worker !== 'background.js') throw new Error('Unexpected extension identity or permissions');
  const archive = createExtensionZip(files);
  const output = '// Generated by scripts/package-douban-extension.mjs; do not edit.\n'
    + 'export const DOUBAN_EXTENSION_ARCHIVE_BASE64 = ' + JSON.stringify(archive.toString('base64')) + ';\n';
  if (check) {
    if (await readFile(generated, 'utf8') !== output) throw new Error('Extension download is stale. Run node scripts/package-douban-extension.mjs');
  } else await writeFile(generated, output);
  return { archive, files, extensionId };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const result = await extensionPackage(process.argv.includes('--check'));
  process.stdout.write(JSON.stringify({ extensionId: result.extensionId, files: result.files.length, bytes: result.archive.length, checked: process.argv.includes('--check') }) + '\n');
}
