import { LocalUserError, localUserId, localUserTime, normalizeLocalEmail, parseLocalUserUpdate, parseNewLocalUser, publicLocalUser } from '../lib/local-users.ts';
import type { LocalUser, LocalUserUpdate, NewLocalUser, PublicLocalUser } from '../lib/local-users.ts';

export type LocalUsersDatabase = Pick<D1Database, 'prepare'>;
const publicColumns = 'id,email,status,revision,created_at AS createdAt,updated_at AS updatedAt,last_login_at AS lastLoginAt';
const internalColumns = `${publicColumns},password_hash AS passwordHash`;
function duplicate(error: unknown): never {
  if (error instanceof Error && /UNIQUE constraint/.test(error.message)) throw new LocalUserError('LOCAL_USER_DUPLICATE');
  throw error;
}

/** Authentication-only: this function intentionally includes the password hash. */
export async function getLocalUserById(db: LocalUsersDatabase, id: string): Promise<LocalUser | null> {
  return db.prepare(`SELECT ${internalColumns} FROM local_users WHERE id=?`).bind(localUserId(id)).first<LocalUser>();
}

/** Authentication-only: this function intentionally includes the password hash. */
export async function getLocalUserByEmail(db: LocalUsersDatabase, email: string): Promise<LocalUser | null> {
  return db.prepare(`SELECT ${internalColumns} FROM local_users WHERE email=? COLLATE NOCASE`).bind(normalizeLocalEmail(email)).first<LocalUser>();
}

/** Bootstrap runs after migrations and never resets a persisted administrator. */
export async function bootstrapLocalOwner(db: LocalUsersDatabase, input: NewLocalUser, now = new Date().toISOString()): Promise<LocalUser> {
  const value = parseNewLocalUser(input, true);
  const existing = await getLocalUserById(db, value.id);
  if (existing) return existing;
  const at = localUserTime(now);
  await db.prepare(`INSERT INTO local_users(id,email,password_hash,status,revision,created_at,updated_at)
    SELECT ?,?,?,'active',1,?,? WHERE NOT EXISTS(SELECT 1 FROM local_users)
    ON CONFLICT DO NOTHING`).bind(value.id, value.email, value.passwordHash, at, at).run();
  const owner = await getLocalUserById(db, value.id);
  if (!owner) throw new LocalUserError('LOCAL_USER_BOOTSTRAP_CONFLICT');
  return owner;
}

/** Caller must authenticate the administrator before enumerating or mutating users. */
export async function listLocalUsers(db: LocalUsersDatabase, ownerId: string): Promise<PublicLocalUser[]> {
  localUserId(ownerId);
  const result = await db.prepare(`SELECT ${publicColumns} FROM local_users ORDER BY CASE WHEN id=? THEN 0 ELSE 1 END,email,id`).bind(ownerId).all<Omit<LocalUser, 'passwordHash'>>();
  return result.results.map(row => publicLocalUser(row, ownerId));
}

/** New member IDs are generated by the caller with crypto.randomUUID(). */
export async function createLocalUser(db: LocalUsersDatabase, input: NewLocalUser, now = new Date().toISOString()): Promise<PublicLocalUser> {
  const value = parseNewLocalUser(input), at = localUserTime(now);
  try {
    const row = await db.prepare(`INSERT INTO local_users(id,email,password_hash,status,revision,created_at,updated_at)
      VALUES(?,?,?,'active',1,?,?) RETURNING ${publicColumns}`).bind(value.id, value.email, value.passwordHash, at, at).first<Omit<LocalUser, 'passwordHash'>>();
    if (!row) throw new LocalUserError('LOCAL_USER_INVALID');
    return publicLocalUser(row, '');
  } catch (error) { return duplicate(error); }
}

/** A single compare-and-swap statement makes competing administrative edits safe. */
export async function updateLocalUser(db: LocalUsersDatabase, ownerId: string, id: string, input: LocalUserUpdate, now = new Date().toISOString()): Promise<PublicLocalUser> {
  localUserId(ownerId); localUserId(id);
  const patch = parseLocalUserUpdate(input), at = localUserTime(now);
  if (id === ownerId && patch.status === 'disabled') throw new LocalUserError('LOCAL_USER_OWNER_PROTECTED');
  try {
    const row = await db.prepare(`UPDATE local_users SET email=COALESCE(?,email),password_hash=COALESCE(?,password_hash),
      status=COALESCE(?,status),revision=revision+1,updated_at=MAX(updated_at,?)
      WHERE id=? AND revision=? AND revision < ? AND (id<>? OR ? IS NULL OR ?='active')
      RETURNING ${publicColumns}`).bind(patch.email ?? null, patch.passwordHash ?? null, patch.status ?? null, at,
      id, patch.expectedRevision, Number.MAX_SAFE_INTEGER, ownerId, patch.status ?? null, patch.status ?? null).first<Omit<LocalUser, 'passwordHash'>>();
    if (row) return publicLocalUser(row, ownerId);
  } catch (error) { return duplicate(error); }
  if (!await getLocalUserById(db, id)) throw new LocalUserError('LOCAL_USER_NOT_FOUND');
  throw new LocalUserError('LOCAL_USER_STALE');
}

/** Login bookkeeping never changes the credential/session revision or edit time. */
export async function touchLocalUserLogin(db: LocalUsersDatabase, id: string, now = new Date().toISOString()): Promise<void> {
  const at = localUserTime(now);
  await db.prepare(`UPDATE local_users SET last_login_at=? WHERE id=? AND status='active'
    AND (last_login_at IS NULL OR last_login_at<?)`).bind(at, localUserId(id), at).run();
}
