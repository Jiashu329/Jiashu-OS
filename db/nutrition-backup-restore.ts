import { BackupCapacityError, backupDigest, backupFail, type DataBackup } from '../lib/data-backup.ts';

type BackupTables = DataBackup['tables'];
type NutritionRows = Pick<BackupTables, 'nutrition_entries' | 'nutrition_day_status' | 'nutrition_favorites'>;

export async function validateNutritionBackupReceipts(tables: BackupTables) {
  for (const row of tables.nutrition_favorites) {
    const template = JSON.parse(String(row.template_json));
    if (await backupDigest(template) === row.template_hash) continue;

    // Adding trusted catalog metadata must not change the identity of an
    // existing favorite. Keep the actual entered amounts in the fingerprint.
    const compatible = { ...template };
    if (template.food) {
      const addedFields = ['carbsTenth', 'proteinTenth', 'fatTenth', 'carbsPer100g', 'proteinPer100g', 'fatPer100g'];
      compatible.food = Object.fromEntries(Object.entries(template.food).filter(([key]) => !addedFields.includes(key)));
    }
    if (compatible.provenance && Object.values(compatible.provenance).every(value => {
      const item = value as Record<string, unknown>;
      return ['manual', 'catalog', 'unknown'].includes(String(item.source)) && !item.basis && !item.portion && !Object.hasOwn(item, 'originalValue');
    })) delete compatible.provenance;
    if (await backupDigest(compatible) !== row.template_hash) backupFail('常用食物的内容摘要与模板不一致。');
  }

  for (const row of tables.nutrition_template_operations) {
    const { id, revision, createdAt: _createdAt, updatedAt: _updatedAt, archivedAt: _archivedAt, ...definition } = JSON.parse(String(row.result_json));
    const expected = row.action === 'create' ? ['create', definition] : [row.action, id, revision - 1, row.action === 'archive' ? null : definition];
    if (await backupDigest(expected) !== row.request_hash) backupFail('食物模板操作回执摘要不一致。');
  }
}

export function planNutritionBackupRestore(current: NutritionRows, additions: NutritionRows) {
  if (current.nutrition_favorites.length + additions.nutrition_favorites.length > 100) {
    throw new BackupCapacityError('恢复后的常用食物将超过100项，未写入数据。请先整理常用食物后重新预览。');
  }

  // Project nutrition_entry_insert_status in the same order as the insert.
  // This includes rows generated by the trigger in the restore capacity check.
  const statuses = new Map(current.nutrition_day_status.map(row => [String(row.date), row]));
  for (const entry of additions.nutrition_entries) {
    const date = String(entry.date);
    const status = statuses.get(date);
    statuses.set(date, {
      date, complete: 0, meals_json: status?.meals_json ?? '{}',
      revision: status ? Number(status.revision) + 1 : 1, updated_at: entry.updated_at,
    });
  }

  // The snapshot guard proves these dates were absent in the target before any
  // inserts. Only their trigger-created placeholders may be replaced.
  for (const row of additions.nutrition_day_status) statuses.set(String(row.date), row);
  return {
    statuses: [...statuses.values()].sort((a, b) => String(a.date).localeCompare(String(b.date))),
    insertSuffix: ' ON CONFLICT(user_id,date) DO UPDATE SET complete=excluded.complete,meals_json=excluded.meals_json,revision=excluded.revision,updated_at=excluded.updated_at',
  };
}
